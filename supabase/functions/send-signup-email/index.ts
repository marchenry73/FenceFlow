// Sends a new FenceFlow account its signup email -- once, ever.
//
// WHY IT EXISTS. FenceFlow used to send exactly one email to a new company,
// and only when that company was READY: details finished AND a trial or plan.
// Someone who created an account and stopped before the details step heard
// nothing at all. On 19 October 2026 a real signup did exactly that and the
// owner asked why no email arrived; nothing was broken, nothing was owed.
// This is the email that was missing. send-welcome-email is unchanged and
// still does its own job.
//
// WHO CALLS IT: one thing only, the profiles_queue_signup_email trigger in
// supabase_r17_signup_email.sql, through pg_net. It fires when a profile with
// role OWNER is inserted -- the moment a real person is attached to a company,
// which is the first instant we know both that someone signed up and where to
// write to them. Triggering on the company row instead would be too early: a
// company can exist for a moment with no owner, and some never get one at all.
//
// THE DOOR: the trigger sends a secret it reads from Vault
// (signup_email_trigger_secret, generated by the migration, never printed) in
// x-fenceflow-signup. This function checks it through signup_email_trigger_ok(),
// which only the service role may call, before it reads the body or anything
// else. verify_jwt is off in config.toml because a database trigger has no
// user session; this check is what replaces it. Even a caller holding the
// secret can only ever cause this one email, to that company's own owner,
// once: the recipient and every word come from the database, never from the
// request.
//
// EXACTLY ONCE: the company is claimed with
//   update companies set signup_sent_at = now()
//    where id = $1 and signup_sent_at is null returning id
// and the email goes only if a row came back. Same rule as the welcome email:
// a 4xx refusal (certainly not sent) releases the claim, a 5xx or no answer
// keeps it, because "maybe not sent" beats "sent twice".
//
// NOT SENT TO: a test company ("ZZ TEST..."), a company with no owner or an
// owner with no email, a company that already has signup_sent_at, or -- and
// this is the one that keeps the two emails from arriving together -- a
// company whose details are ALREADY done. Someone who signs up and finishes
// setup in one sitting gets only the welcome email, which is the better of
// the two for them.
//
// Mail goes through the same provider and secrets as send-welcome-email
// (MAIL_API_KEY, MAIL_FROM, MAIL_API_URL, MAIL_FROM_NAME), from FenceFlow
// itself, with replies going to support. No address is written to the logs.
import { createClient } from "https://esm.sh/@supabase/supabase-js@2.39.0";
import { buildSignupEmail } from "../_shared/signup-email.ts";

const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json" } });

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
// encode(gen_random_bytes(32), 'hex') in the migration: 64 hex characters.
const SECRET_RE = /^[0-9a-f]{64}$/;

/** "FenceFlow <x@y>" -- the bare address when MAIL_FROM already has a name. */
function senderWithName(name: string, address: string): string {
  const clean = name.replace(/[\r\n<>"]/g, "").trim().slice(0, 70);
  if (!clean || address.includes("<")) return address;
  return `"${clean}" <${address}>`;
}

Deno.serve(async (req) => {
  if (req.method !== "POST") return json({ error: "method not allowed" }, 405);

  let companyId = "";
  const log = (outcome: string, extra: Record<string, unknown> = {}) =>
    console.log(JSON.stringify({ fn: "send-signup-email", outcome, company: companyId || null, ...extra }));

  try {
    const admin = createClient(
      Deno.env.get("SUPABASE_URL")!,
      Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!,
    );

    // The door, before anything else is read.
    const supplied = (req.headers.get("x-fenceflow-signup") ?? "").trim();
    if (!SECRET_RE.test(supplied)) return json({ error: "unauthorized" }, 401);
    const { data: allowed, error: allowErr } = await admin.rpc("signup_email_trigger_ok", { p_secret: supplied });
    if (allowErr) {
      log("error", { stage: "door", reason: allowErr.message });
      return json({ error: "could not check the caller" }, 500);
    }
    if (allowed !== true) return json({ error: "unauthorized" }, 401);

    const body = await req.json().catch(() => ({}));
    companyId = String(body?.company_id ?? "").trim();
    if (!UUID_RE.test(companyId)) {
      companyId = "";
      return json({ error: "bad request" }, 400);
    }

    const mailKey = Deno.env.get("MAIL_API_KEY");
    const mailFrom = Deno.env.get("MAIL_FROM");
    const mailUrl = Deno.env.get("MAIL_API_URL") ?? "https://api.resend.com/emails";
    const fromName = Deno.env.get("MAIL_FROM_NAME") ?? "FenceFlow";
    const site = (Deno.env.get("SITE_URL") ?? "https://fenceflowapp.com").replace(/\/+$/, "");
    const support = Deno.env.get("SUPPORT_EMAIL") ?? "support@fenceflowapp.com";
    if (!mailKey || !mailFrom) {
      // Nothing claimed, so nothing is lost but this one email.
      log("not_configured");
      return json({ error: "mail not configured" }, 503);
    }

    const { data: company, error: coErr } = await admin
      .from("companies")
      .select("id, name, details_completed_at, signup_sent_at")
      .eq("id", companyId)
      .maybeSingle();
    if (coErr) {
      log("error", { stage: "company", reason: coErr.message });
      return json({ error: "could not read the company" }, 500);
    }
    if (!company) { log("skipped", { reason: "no such company" }); return json({ skipped: "no such company" }); }
    if (company.signup_sent_at) { log("skipped", { reason: "already sent" }); return json({ skipped: "already sent" }); }
    // The whole point of the skip: they are past this email already, and the
    // welcome one says everything this would have said and more.
    if (company.details_completed_at) {
      log("skipped", { reason: "details already done" });
      return json({ skipped: "details already done" });
    }
    if (/^\s*zz test/i.test(String(company.name ?? ""))) {
      log("skipped", { reason: "test company" });
      return json({ skipped: "test company" });
    }

    // The owner who signed up, at the address their login uses. Never the
    // company's typed contact email: that is a field the owner can set to
    // anything, and this is FenceFlow's own domain sending.
    const { data: owner, error: ownerErr } = await admin
      .from("profiles")
      .select("id, full_name")
      .eq("company_id", companyId)
      .eq("role", "OWNER")
      .order("created_at", { ascending: true })
      .limit(1)
      .maybeSingle();
    if (ownerErr) {
      log("error", { stage: "owner", reason: ownerErr.message });
      return json({ error: "could not read the owner" }, 500);
    }
    if (!owner) { log("skipped", { reason: "no owner" }); return json({ skipped: "no owner" }); }
    const { data: account, error: accountErr } = await admin.auth.admin.getUserById(owner.id);
    if (accountErr) {
      log("error", { stage: "account", reason: accountErr.message });
      return json({ error: "could not read the owner's account" }, 500);
    }
    const to = String(account?.user?.email ?? "").trim();
    if (!to) { log("skipped", { reason: "owner has no email" }); return json({ skipped: "owner has no email" }); }

    // The claim. Only the caller that gets the row back sends.
    const { data: claimed, error: claimErr } = await admin
      .from("companies")
      .update({ signup_sent_at: new Date().toISOString() })
      .eq("id", companyId)
      .is("signup_sent_at", null)
      .select("id");
    if (claimErr) {
      log("error", { stage: "claim", reason: claimErr.message });
      return json({ error: "could not claim the company" }, 500);
    }
    if (!claimed || claimed.length === 0) {
      log("skipped", { reason: "already sent" });
      return json({ skipped: "already sent" });
    }

    const email = buildSignupEmail({
      companyName: company.name,
      ownerName: owner.full_name,
      recipientEmail: to,
      setupUrl: `${site}/welcome.html`,
      supportEmail: support,
    });

    let res: Response;
    try {
      res = await fetch(mailUrl, {
        method: "POST",
        headers: { Authorization: `Bearer ${mailKey}`, "Content-Type": "application/json" },
        body: JSON.stringify({
          from: senderWithName(fromName, mailFrom),
          to: [to],
          reply_to: support,
          subject: email.subject,
          html: email.html,
          text: email.text,
        }),
      });
    } catch (_e) {
      // No answer: it may have gone out, so the claim stays.
      log("error", { stage: "send", reason: "no answer from the mail provider" });
      return json({ error: "could not reach the mail provider" }, 502);
    }

    if (!res.ok) {
      const detail = (await res.text().catch(() => "")).slice(0, 300);
      if (res.status >= 400 && res.status < 500) {
        // Refused outright, so certainly not sent: give the claim back.
        await admin.from("companies").update({ signup_sent_at: null }).eq("id", companyId);
      }
      log("refused", { status: res.status, detail });
      return json({ error: `mail provider answered ${res.status}` }, 502);
    }

    const sent = await res.json().catch(() => ({}));
    log("sent", { provider_id: sent?.id ? String(sent.id) : null });
    return json({ sent: true });
  } catch (e) {
    log("error", { stage: "unexpected", reason: String(e instanceof Error ? e.message : e) });
    return json({ error: "unexpected error" }, 500);
  }
});
