package com.fenceestimator.app.cloud

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * AES/GCM against a key held in the Android Keystore, for the few things on
 * this phone that are credentials rather than data.
 *
 * WHAT THIS IS FOR, AND WHY IT EXISTS AT ALL. supabase-kt installs
 * SettingsSessionManager by default on Android, which keeps the session in
 * multiplatform-settings -- SharedPreferences, plain XML in the app's data
 * directory. MEASURED 7 Nov 2026 by reading auth-kt-release.aar 3.0.2: that
 * is the class that ships, and FenceFlow installs Auth with no override. So
 * the signed-in contractor's REFRESH TOKEN has been sitting unencrypted on
 * every handset. A refresh token is not a password but it is worth as much as
 * one: anyone who can read the file can mint sessions as that account until it
 * is revoked -- a backup, a rooted phone, a handset that changes hands.
 *
 * NOT androidx.security-crypto. Its maintained line is alpha and pulls Tink,
 * and this project pins dependencies on purpose (androidx.browser is held at
 * 1.8.0 a few lines from here, for exactly that reason). The platform Keystore
 * needs no dependency at all, and nothing here invents a cipher: it is the
 * standard AES/GCM-with-a-Keystore-key pattern.
 *
 * THE KEY NEVER LEAVES THE KEYSTORE. It is generated on first use, marked
 * non-exportable by construction (a Keystore key has no getEncoded), and is
 * destroyed with the app's data. Nothing here persists the key, only the
 * ciphertext.
 *
 * setUserAuthenticationRequired is deliberately FALSE. The app has to read its
 * own session when the process starts, long before anybody has touched the
 * biometric prompt, and a key that demanded authentication would lock the
 * phone out of its own sync. Screen-lock is handled separately by the app's
 * own auto-lock and biometric gate; this key exists to stop the file being
 * readable OFF the device, which is the exposure it is named for.
 *
 * EVERY FAILURE RETURNS NULL, NEVER THROWS. A Keystore key can genuinely go
 * away -- the OS discards them on some restore paths and some OEM upgrades --
 * and when it does, the ciphertext is permanently unreadable. The honest
 * answer then is "there is no session", which puts the contractor on the
 * sign-in screen. A thrown exception here would instead take the app down on
 * launch, on the one path that cannot be retried.
 */
object DeviceCipher {

    private const val KEYSTORE = "AndroidKeyStore"
    /** v1 in the name so a future scheme can coexist rather than silently fail to decrypt. */
    private const val ALIAS = "fenceflow_credential_key_v1"
    private const val TRANSFORM = "AES/GCM/NoPadding"
    private const val TAG_BITS = 128
    private const val IV_BYTES = 12

    /**
     * The key, made once and reused. Synchronised because two coroutines can
     * reach a cold Keystore at the same moment on a cold start, and
     * generateKey twice would leave the second holding a key that cannot read
     * what the first wrote.
     */
    @Synchronized
    private fun key(): SecretKey? = runCatching {
        val store = KeyStore.getInstance(KEYSTORE).apply { load(null) }
        (store.getKey(ALIAS, null) as? SecretKey) ?: run {
            val gen = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE)
            gen.init(
                KeyGenParameterSpec.Builder(
                    ALIAS,
                    KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
                )
                    .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                    .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                    // See the class comment: the app must read its own session
                    // before any prompt could be shown.
                    .setUserAuthenticationRequired(false)
                    .build()
            )
            gen.generateKey()
        }
    }.getOrNull()

    /**
     * Base64 of (iv || ciphertext), or null if the key is unavailable.
     *
     * The IV is generated by the cipher, never reused and never chosen here --
     * a repeated IV under one GCM key is the way this construction is
     * normally broken, and the platform picks a fresh one per operation.
     */
    fun encrypt(plain: String): String? = runCatching {
        val k = key() ?: return null
        val cipher = Cipher.getInstance(TRANSFORM).apply { init(Cipher.ENCRYPT_MODE, k) }
        val iv = cipher.iv
        require(iv.size == IV_BYTES) { "unexpected GCM IV length ${iv.size}" }
        val ct = cipher.doFinal(plain.toByteArray(Charsets.UTF_8))
        Base64.encodeToString(iv + ct, Base64.NO_WRAP)
    }.getOrNull()

    /**
     * The plaintext, or null for anything that is not a value this object
     * wrote with the key it still has: a short blob, a tampered one, a
     * different scheme, or a key the OS has discarded.
     */
    fun decrypt(blob: String): String? = runCatching {
        val k = key() ?: return null
        val raw = Base64.decode(blob, Base64.NO_WRAP)
        // Shorter than an IV plus a tag cannot be ours, and feeding it to the
        // cipher would throw rather than answer.
        if (raw.size <= IV_BYTES + TAG_BITS / 8) return null
        val cipher = Cipher.getInstance(TRANSFORM).apply {
            init(
                Cipher.DECRYPT_MODE, k,
                GCMParameterSpec(TAG_BITS, raw, 0, IV_BYTES),
            )
        }
        String(cipher.doFinal(raw, IV_BYTES, raw.size - IV_BYTES), Charsets.UTF_8)
    }.getOrNull()
}
