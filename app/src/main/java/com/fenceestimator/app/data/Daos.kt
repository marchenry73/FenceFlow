@Dao
interface MaterialItemDao {
    // ORDER BY is load-bearing here, not cosmetic. Without it SQLite returns
    // rows in whatever order the storage engine likes, and the estimate
    // engine breaks ties by list position -- so the same drawing repriced
    // twice could pick a DIFFERENT product for the same role, and the
    // customer watched their quote flip between the white panel at $52.35
    // and the gray one at $54.50 "by itself".
    @Query("SELECT * FROM material_items ORDER BY category, name, id")
    suspend fun getAll(): List<MaterialItem>
    @Query("SELECT * FROM material_items WHERE isActive = 1 ORDER BY category, name")
    fun observeAllActive(): Flow<List<MaterialItem>>

    @Query("SELECT * FROM material_items ORDER BY category, name")
    fun observeAll(): Flow<List<MaterialItem>>

    @Query("SELECT * FROM material_items WHERE id = :id")
    suspend fun getById(id: Long): MaterialItem?

    @Query("SELECT * FROM material_items WHERE role = :role AND isActive = 1 ORDER BY coversFt ASC")
    suspend fun getByRole(role: MaterialRole): List<MaterialItem>

    @Query("SELECT COUNT(*) FROM material_items")
    suspend fun count(): Int

    /**
     * Removes catalog duplicates from the old double-seeding bug. Matches on
     * name+role+fenceType+colorOrFinish so genuinely different items (same
     * name, different manufacturer price) are left alone.
     */
    @Query(
        "DELETE FROM material_items WHERE id NOT IN (" +
            "SELECT MIN(id) FROM material_items " +
            "GROUP BY name, role, fenceType, colorOrFinish, IFNULL(manufacturerId, -1))"
    )
    suspend fun deleteDuplicates(): Int

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insert(item: MaterialItem): Long

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertAll(items: List<MaterialItem>)

    @Update
    suspend fun update(item: MaterialItem)

    @Delete
    suspend fun delete(item: MaterialItem)
}

@Dao
interface EstimateLineItemDao {
    @Query("SELECT * FROM estimate_line_items WHERE jobId = :jobId ORDER BY sortOrder ASC, syncId ASC")
    fun observeForJob(jobId: Long): Flow<List<EstimateLineItem>>

    @Query("SELECT * FROM estimate_line_items WHERE jobId = :jobId ORDER BY sortOrder ASC, syncId ASC")
    suspend fun getForJob(jobId: Long): List<EstimateLineItem>

    /** Every line item in one query, for figures that span all jobs. */
    @Query("SELECT * FROM estimate_line_items ORDER BY sortOrder ASC, syncId ASC")
    suspend fun getAll(): List<EstimateLineItem>

    @Insert
    suspend fun insert(item: EstimateLineItem): Long

    @Insert
    suspend fun insertAll(items: List<EstimateLineItem>)

    @Update
    suspend fun update(item: EstimateLineItem)

    @Delete
    suspend fun delete(item: EstimateLineItem)

    @Query("DELETE FROM estimate_line_items WHERE fenceRunId = :runId AND isAutoGenerated = 1")
    suspend fun deleteAutoGeneratedForRun(runId: Long)

    /**
     * Clears everything the takeoff produced for this run. Keyed on role rather
     * than the auto-generated flag because editing a line clears that flag --
     * so the old delete skipped edited lines and the next Suggest added a second
     * copy of each one. Hand-typed extras have no role and are left alone.
     */
    // role != 'NONE', not "role is not null". The column is not nullable -- it
    // stores the enum name and defaults to NONE -- so a null check matches every
    // row, which would take hand-typed extras with it if one were ever attached
    // to a run. NONE is what "no material role" actually looks like here.
    @Query("DELETE FROM estimate_line_items WHERE fenceRunId = :runId AND role != 'NONE'")
    suspend fun deleteGeneratedForRun(runId: Long)

    @Query("SELECT * FROM estimate_line_items WHERE fenceRunId = :runId AND role != 'NONE'")
    suspend fun getGeneratedForRun(runId: Long): List<EstimateLineItem>

    /**
     * Delete and re-insert as one unit. Two quick taps on Suggest Quantities
     * used to interleave -- both deletes ran, then both inserts -- which is the
     * other way the estimate ended up with everything twice.
     */
    @Transaction
    suspend fun replaceGeneratedForRun(runId: Long, items: List<EstimateLineItem>) {
        deleteGeneratedForRun(runId)
        insertAll(items)
    }

    @Query("DELETE FROM estimate_line_items WHERE jobId = :jobId")
    suspend fun deleteAllForJob(jobId: Long)

    /**
     * Takeoff lines that lost their fence run. Only the old cloud pull could
     * produce these.
     *
     * Matched on role != 'NONE', NOT on "role is not null". The column is not
     * nullable -- it stores the enum name and defaults to NONE -- so a null
     * check is always true and would delete the user's hand-typed extras along
     * with the orphans. A hand-typed item has no material role, which is what
     * NONE means, and that is what keeps it safe here.
     */
    @Query("DELETE FROM estimate_line_items WHERE fenceRunId IS NULL AND role != 'NONE'")
    suspend fun deleteOrphanedGenerated(): Int

    /** The orphans, so their cloud copies can be tombstoned before they are removed. */
    @Query("SELECT * FROM estimate_line_items WHERE fenceRunId IS NULL AND role != 'NONE'")
    suspend fun orphanedGenerated(): List<EstimateLineItem>
}

