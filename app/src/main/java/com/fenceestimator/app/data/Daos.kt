/**
 * Removes local rows that another device deleted.
 *
 * One raw-query DAO rather than thirteen near-identical `DELETE ... WHERE
 * syncId IN (...)` methods, because the difference between them is only the
 * table name and thirteen copies is thirteen chances to miss one when a table
 * is added.
 *
 * The table name is interpolated, which would be an injection risk if it came
 * from anywhere but a fixed list in [SyncTables]. It never does -- the values
 * are compile-time constants, and the sync ids are bound as parameters.
 */
@Dao
interface SyncMaintenanceDao {
    @RawQuery
    suspend fun execute(query: androidx.sqlite.db.SupportSQLiteQuery): Int
}

/** Every table that syncs, so the reaper and the pusher cannot drift apart. */
object SyncTables {
    /** Local Room table name to the cloud table it maps to; they match today. */
    val ALL: List<String> = listOf(
        "fence_runs", "estimate_line_items", "change_orders", "job_steps",
        "site_markers", "time_entries", "expenses", "punch_list_items",
        "employees", "manufacturers", "material_items", "pricing_tiers",
        "field_changes"
    )
}

@Dao
interface PaymentRecordDao {
    @Query("SELECT * FROM payment_records WHERE jobId = :jobId ORDER BY receivedAt DESC")
    fun observeForJob(jobId: Long): Flow<List<PaymentRecord>>

    @Query("SELECT * FROM payment_records ORDER BY receivedAt DESC")
    fun observeAll(): Flow<List<PaymentRecord>>

    @Query("SELECT * FROM payment_records")
    suspend fun getAll(): List<PaymentRecord>

    /** The money that actually moved inside a period -- what a report should count. */
    @Query("SELECT * FROM payment_records WHERE receivedAt BETWEEN :fromMillis AND :toMillis ORDER BY receivedAt DESC")
    suspend fun getBetween(fromMillis: Long, toMillis: Long): List<PaymentRecord>

    @Query("SELECT COALESCE(SUM(amount), 0) FROM payment_records WHERE jobId = :jobId")
    suspend fun netForJob(jobId: Long): Double

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insert(record: PaymentRecord): Long

    @Insert(onConflict = OnConflictStrategy.IGNORE)
    suspend fun insertAll(records: List<PaymentRecord>)

    @Query("SELECT * FROM payment_records WHERE syncId = :syncId LIMIT 1")
    suspend fun bySyncId(syncId: String): PaymentRecord?

    @Query("DELETE FROM payment_records WHERE syncId IN (:syncIds)")
    suspend fun deleteBySyncIds(syncIds: List<String>): Int
}
