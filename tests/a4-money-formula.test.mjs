console.log("\n7. CANARIES -- one rule broken per scratch copy of the engine; each must turn its named checks RED:");

/**
 * Copy the whole pricing directory to a fresh temp dir, apply `patches`
 * (each { file, find, replace } -- `find` is a RegExp or an exact string that
 * MUST match, or the canary is reported as not having fired), import the
 * scratch engine and hand it to runChecks.
 */
async function withBrokenEngine(label, patches, mustFail) {
  const root = mkdtempSync(join(tmpdir(), "a4-formula-"));
  try {
    const dir = join(root, "pricing");
    cpSync(REAL_PRICING_DIR, dir, { recursive: true });
    let applied = true;
    for (const p of patches) {
      const path = join(dir, p.file);
      const src = readFileSync(path, "utf8");
      const next = src.replace(p.find, p.replace);
      if (next === src) { applied = false; break; }
      writeFileSync(path, next);
    }
    // A patch that did not match means the scratch engine is a COPY OF THE
    // REAL ONE and every check below would pass by comparing the engine with
    // itself -- which reads exactly like "the rule is well guarded". That is
    // the a18 lesson, so it is a loud failure of its own.
    if (!applied) {
      ok(`CANARY ${label}: the rule's source text was found and broken`, false,
        "a patch did not match -- the scratch engine is identical to the real one, so this canary proves NOTHING. " +
        "The rule has probably been re-spelled; update the needle.");
      return;
    }
    ok(`CANARY ${label}: the rule's source text was found and broken`, true);

    const mod = await import(pathToFileURL(join(dir, "index.ts")).href);
    let broken;
    try {
      broken = runChecks(mod.priceJob, mod.PRICING_ENGINE_VERSION);
    } catch (e) {
      // A break that makes the engine throw is still a break the checks
      // noticed, but it is not evidence about WHICH check has teeth.
      ok(`CANARY ${label}: the broken engine still prices (so the red checks below are about arithmetic, not a crash)`,
        false, String(e.message).slice(0, 160));
      return;
    }
    const reds = Object.entries(broken).filter(([, r]) => !r.pass).map(([id]) => id);
    for (const id of mustFail) {
      ok(`CANARY ${label}: [${id}] goes RED`, reds.includes(id),
        `red checks were: ${reds.join(", ") || "(none -- this check cannot fail)"}`);
    }
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

