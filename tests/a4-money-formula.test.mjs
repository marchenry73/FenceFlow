const r2 = (v) => (Number.isFinite(v) ? Math.round(v * 100) / 100 : v);

/**
 * The intended formula, recomputed from a fixture's OWN job settings and its
 * OWN recorded component figures, then measured against the grand total and
 * labour figure Kotlin recorded. Returns the list of rules this fixture
 * violates, so a clean fixture returns [].
 *
 * Labour is rebuilt from billable_linear_feet - gate_feet, which is exactly
 * what EstimateEngine.computeTotals charges it on, so the $200 floor and the
 * "the gate is not fence labour" subtraction are both under test here, not
 * assumed.
 */
function violationsOf(fixture) {
  const t = fixture.expected.totals, j = fixture.input.job, bad = [];
  const near = (a, b, eps = 1e-9) => Math.abs(a - b) <= eps;

  // R1 tax base.
  if (!near(t.tax, t.taxable_subtotal * (j.tax_rate_percent / 100))) bad.push("tax-base");
  // R3 the markup base holds tax and every service term, and nothing else.
  const pre = t.materials_subtotal + t.tax + t.labor_cost + t.teardown_cost + t.change_order_cost + t.gate_charge;
  if (!near(t.pre_markup_total, pre)) bad.push("markup-base");
  if (!near(t.markup_amount, t.pre_markup_total * (j.markup_percent / 100))) bad.push("markup");
  // R3 the discount is taken on the marked-up figure.
  if (!near(t.discount_amount, (t.pre_markup_total + t.markup_amount) * (j.discount_percent / 100))) bad.push("discount-base");
  // R2 + R4 the job floor is applied last, then rounded once.
  const chain = t.pre_markup_total + t.markup_amount - t.discount_amount;
  if (!near(t.grand_total, r2(Math.max(chain, j.minimum_job_charge || 0)))) bad.push("grand-total");
  // R2 the labour floor, over labour alone, on fence feet less gate feet.
  const laborFeet = Math.max(t.billable_linear_feet - (t.gate_feet || 0), 0);
  const rawLabor = j.labor_flat_fee + j.labor_rate_per_ft * laborFeet;
  const expectLabor = j.minimum_labor_charge > 0 ? Math.max(rawLabor, j.minimum_labor_charge) : rawLabor;
  // 2e-3: billable_linear_feet is a Kotlin Float in the fixture, so a long
  // run's footage carries f32 error that the labour RATE multiplies up.
  // Nothing smaller than a fifth of a cent passes, which is far below any
  // real pricing mistake and far above f32 noise.
  if (!near(t.labor_cost, expectLabor, 2e-3)) bad.push("labour-floor");
  // R4 the recorded total is on the cent.
  if (!near(t.grand_total, r2(t.grand_total))) bad.push("not-on-cents");
  return bad;
}

