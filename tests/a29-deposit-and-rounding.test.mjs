// tests/a29-deposit-and-rounding.test.mjs
//
// 1 Oct 2026. Two decisions the owner took, knowing what each costs:
//
//   1. THE TOTAL IS EXACT. grand_total used to be ceil(max(afterDiscount,
//      minimumJobCharge) / 10) * 10. It is now roundToCents(...): the same
//      figure to the cent, in both engines, with the engine version bumped.
//   2. THE DEPOSIT is the materials still to be bought, rounded UP to the next
//      $100, plus another $100 -- never more than is still owed. The extra
//      $100 is not disclosed to the customer.
//
// What this file holds, and what it deliberately does not:
//   - the shared vectors (tests/a29-deposit-rule-vectors.json) against the
//     TypeScript side. Kotlin runs the SAME file in JobMoneyDepositRuleTest.kt;
//   - the engine, run for real (priceJob), exact to the cent, with the minimum
//     job charge reading exactly the minimum;
//   - quote-view's own fallback total, run for real against a fake database;
//   - the version, on both sides, pinned equal and moved;
//   - that the quote page never adds the extra hundred itself.
// It does NOT replay the parity fixtures. Those are regenerated by the gate,
// after a clean test compile, and not here.
//
// Every rule has a planted failure beside it: the figure the OLD behaviour
// gives for the same input, asserted to differ, so a test that would pass
// whichever rule ran cannot hide in here.
//
// Run with: node --test tests/a29-deposit-and-rounding.test.mjs

