// ============================================================ rounding ====

test("roundToCents: every shared vector, through BOTH TypeScript copies (the page's and the engine's)", () => {
  assert.ok(vectors.roundToCents.length >= 10, "the vector file lost its rows");
  for (const v of vectors.roundToCents) {
    assert.equal(roundToCents(v.in), v.out, `${v.name}: quote-deposit roundToCents(${v.in})`);
    assert.equal(engineRoundToCents(v.in), v.out, `${v.name}: pricing/totals roundToCents(${v.in})`);
  }
  for (const bad of [NaN, Infinity, -Infinity]) {
    assert.ok(Object.is(engineRoundToCents(bad), roundToCents(bad)), `non-finite ${bad}`);
  }
});

test("PLANTED: the old round-up-to-ten gives a different answer for almost every vector", () => {
  // If this stopped differing, the vectors above would pass under either rule.
  const differing = vectors.roundToCents.filter((v) => v.in > 0 && oldCeilTen(v.in) !== v.out);
  assert.ok(differing.length >= 8, `only ${differing.length} vectors tell the two rules apart`);
  assert.equal(oldCeilTen(2114.633), 2120);
  assert.equal(roundToCents(2114.633), 2114.63);
});

test("roundToCents leaves a non-finite value visibly broken instead of turning NaN into $0", () => {
  assert.ok(Number.isNaN(roundToCents(NaN)));
  assert.equal(roundToCents(Infinity), Infinity);
  assert.equal(roundToCents(-Infinity), -Infinity);
});

test("roundToCents is idempotent, so rounding an already-exact total changes nothing", () => {
  for (const v of vectors.roundToCents) {
    assert.equal(roundToCents(roundToCents(v.in)), roundToCents(v.in), v.name);
  }
});

