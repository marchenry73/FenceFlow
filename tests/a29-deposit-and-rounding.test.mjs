const kotlinVersion = /const val PRICING_ENGINE_VERSION = "([^"]+)"/.exec(read("app/src/main/java/com/fenceestimator/app/estimate/EstimateEngine.kt"))?.[1];
const versionIsNewer = (a, b) => {
  const x = a.split(".").map(Number), y = b.split(".").map(Number);
  for (let i = 0; i < Math.max(x.length, y.length); i++) if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) > (y[i] ?? 0);
  return false;
};

test("version: Kotlin and TypeScript carry the SAME engine version", () => {
  assert.ok(kotlinVersion, "could not read PRICING_ENGINE_VERSION out of EstimateEngine.kt");
  assert.equal(PRICING_ENGINE_VERSION, kotlinVersion);
});

test("version: the rounding is a formula change, so the version moved off 2026.09.3", () => {
  assert.notEqual(PRICING_ENGINE_VERSION, "2026.09.3");
  assert.ok(versionIsNewer(PRICING_ENGINE_VERSION, "2026.09.3"),
    "JobSync.engineVersionIsNewer compares component by component: the bump must be NEWER or an old office row reads as ahead of the phone");
  // 2026.10.1 against 2026.09.3: component two is 10 vs 9, which a string compare of "2026.10.1" < "2026.9.3" would get backwards.
  assert.ok(versionIsNewer("2026.10.1", "2026.9.3"));
});

