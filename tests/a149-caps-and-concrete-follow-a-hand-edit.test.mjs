/* CAPS AND CONCRETE FOLLOW A HAND-EDITED POST COUNT.
 *
 * "Yes make the caps and concrete follow my edit."
 *
 * He set one side's end posts to 1 by hand and another's blank posts to 1.
 * Both edits stood -- that is what a hand edit is for -- but the post caps and
 * the concrete went on being priced off the ENGINE's count, so the quote
 * billed 15 caps and 15 bags against 14 posts on one side, and 2 caps against
 * 1 post on another. One screen, two answers.
 *
 * The rule, one line each:
 *   caps     move by the total change in posts, whatever the role
 *   concrete moves by the change in NON-GATE posts only
 *
 * because a gate's bags belong to the gate and not to the post tally -- the
 * rule takeoff.ts already follows ("Gate posts are left out here and paid for
 * by the gate itself").
 *
 * Done in the MERGE rather than the engine: the engine prices the drawing and
 * has no idea a line was edited, while the merge is exactly where an edit
 * meets the engine's answer. That is also why no fixture moves and the engine
 * version does not bump -- parity reports 90 of 90 unchanged, asserted below
 * so that claim cannot quietly stop being true.
 *
 *   node --test tests/a149-caps-and-concrete-follow-a-hand-edit.test.mjs
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { mergeTakeoff } from "../supabase/functions/_shared/pricing/line-items.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(resolve(ROOT, p), "utf8").split("\r\n").join("\n");

let n = 0;
/** A line. `auto` false is one he changed by hand. */
const L = (role, quantity, { auto = true, id = null, description = "" } = {}) => ({
  syncId: id ?? `L${++n}`,
  role,
  quantity,
  unitPrice: 1,
  description,
  isAutoGenerated: auto,
});

/** The engine's answer for a plain 14-post side: 11 line, 2 end, 1 corner. */
const builtFence = () => [
  L("LINE_POST", 11, { id: "b-line" }),
  L("END_POST", 2, { id: "b-end" }),
  L("CORNER_POST", 1, { id: "b-corner" }),
  L("POST_CAP", 14, { id: "b-cap" }),
  L("CONCRETE_BAG", 14, { id: "b-bag" }),
];

const qtyOf = (merge, role) => {
  const all = [...merge.insert, ...merge.keptEdited].filter((i) => i.role === role);
  return all.reduce((t, i) => t + i.quantity, 0);
};

test("no hand-edited post: nothing moves at all", () => {
  const built = builtFence();
  const merge = mergeTakeoff([], built, 1);
  assert.equal(qtyOf(merge, "POST_CAP"), 14);
  assert.equal(qtyOf(merge, "CONCRETE_BAG"), 14);
  // And an edit to something that is NOT a post leaves the posts alone.
  const withPanelEdit = mergeTakeoff([L("PANEL", 99, { auto: false, id: "b-panel" })], built, 1);
  assert.equal(qtyOf(withPanelEdit, "POST_CAP"), 14);
  assert.equal(qtyOf(withPanelEdit, "CONCRETE_BAG"), 14);
});

test("end posts 2 -> 1 takes a cap and a bag with it", () => {
  // His Side 1, exactly: the edit stands, and the two numbers derived from it
  // follow instead of contradicting it.
  const built = builtFence();
  const edited = [L("END_POST", 1, { auto: false, id: "b-end" })];
  const merge = mergeTakeoff(edited, built, 1);
  assert.equal(qtyOf(merge, "END_POST"), 1, "his edit did not survive");
  assert.equal(qtyOf(merge, "POST_CAP"), 13, "the cap did not follow the post");
  assert.equal(qtyOf(merge, "CONCRETE_BAG"), 13, "the bag did not follow the post");
});

test("a gate's blank post takes its cap but NOT a bag", () => {
  // The gate's concrete is the gate's. Editing the post it hangs on must not
  // reach into the bags the gate itself asked for.
  const built = [
    L("BLANK_POST", 2, { id: "b-blank" }),
    L("POST_CAP", 2, { id: "b-cap" }),
    L("CONCRETE_BAG", 1, { id: "b-bag" }),
  ];
  const merge = mergeTakeoff([L("BLANK_POST", 1, { auto: false, id: "b-blank" })], built, 1);
  assert.equal(qtyOf(merge, "BLANK_POST"), 1);
  assert.equal(qtyOf(merge, "POST_CAP"), 1, "the cap did not follow the gate post");
  assert.equal(qtyOf(merge, "CONCRETE_BAG"), 1, "the gate's own bag moved, and it must not");
});

test("adding posts by hand adds caps and bags, at the run's bags-per-post", () => {
  const built = builtFence();
  // 11 -> 14 line posts, and this run sets two bags per hole.
  const merge = mergeTakeoff([L("LINE_POST", 14, { auto: false, id: "b-line" })], built, 2);
  assert.equal(qtyOf(merge, "POST_CAP"), 17, "three posts added, three caps expected");
  assert.equal(qtyOf(merge, "CONCRETE_BAG"), 20, "three posts at two bags each");
});

test("a post he added that the drawing never asked for counts in full", () => {
  const built = builtFence();
  // No built GATE_POST at all: this is a line he put on himself.
  const merge = mergeTakeoff([L("GATE_POST", 2, { auto: false, id: "mine" })], built, 1);
  assert.equal(qtyOf(merge, "POST_CAP"), 16, "two posts added, two caps expected");
  // A gate post, so no run concrete.
  assert.equal(qtyOf(merge, "CONCRETE_BAG"), 14, "a gate post must not add run concrete");
});

test("an edit matched BY ROLE uses what that line was, not its whole quantity", () => {
  // The bug this nearly shipped with. claimedByEdits pairs by sync id first
  // and then BY ROLE, and reading only the id map scored a role-matched edit's
  // entire quantity as new posts -- one fixture's caps went 18 -> 34.
  const built = builtFence();
  const edited = [L("END_POST", 1, { auto: false, id: "an-id-the-build-no-longer-makes" })];
  const merge = mergeTakeoff(edited, built, 1);
  assert.equal(qtyOf(merge, "END_POST"), 1);
  assert.equal(qtyOf(merge, "POST_CAP"), 13, "the role-matched edit was scored as a new post, not a change");
});

test("a cap or bag HE edited is never overwritten by a number derived from his posts", () => {
  const built = builtFence();
  const merge = mergeTakeoff(
    [L("END_POST", 1, { auto: false, id: "b-end" }), L("POST_CAP", 99, { auto: false, id: "b-cap" })],
    built, 1,
  );
  assert.equal(qtyOf(merge, "POST_CAP"), 99, "his own cap number was overwritten");
  // The bag he did not touch still follows.
  assert.equal(qtyOf(merge, "CONCRETE_BAG"), 13);
});

test("a quantity can never be driven below zero", () => {
  const built = builtFence();
  const merge = mergeTakeoff([L("LINE_POST", 0, { auto: false, id: "b-line" })], built, 1);
  assert.equal(qtyOf(merge, "POST_CAP"), 3);
  assert.ok(qtyOf(merge, "CONCRETE_BAG") >= 0);
  // Taking out more posts than exist cannot make a negative order.
  const silly = mergeTakeoff([L("LINE_POST", -99, { auto: false, id: "b-line" })], built, 1);
  assert.ok(qtyOf(silly, "POST_CAP") >= 0);
  assert.ok(qtyOf(silly, "CONCRETE_BAG") >= 0);
});

test("the engine version is NOT bumped, because no recorded case moves", () => {
  // The claim this change rests on. If a future edit here starts moving
  // fixtures, parity goes red and this assertion says why that matters.
  const ts = read("supabase/functions/_shared/pricing/index.ts");
  const kt = read("app/src/main/java/com/fenceestimator/app/estimate/EstimateEngine.kt");
  const v = ts.match(/PRICING_ENGINE_VERSION = "([^"]+)"/)[1];
  assert.equal(kt.match(/PRICING_ENGINE_VERSION = "([^"]+)"/)[1], v, "the two engines disagree about their version");
  const manifest = JSON.parse(read("fixtures/pricing/manifest.json"));
  assert.equal(manifest.version, v, "the fixtures were generated by a different engine version than the code claims");
});

test("POSITIVE CONTROL: the helper really runs, and really can fail", () => {
  // Every check above would pass against a mergeTakeoff that ignored the
  // bagsPerPost argument entirely, if the caps happened to be right. Asserted
  // directly: the same edit at a different bags-per-post must give different
  // concrete, and an unedited run must give the same.
  const built = builtFence();
  const one = qtyOf(mergeTakeoff([L("END_POST", 1, { auto: false, id: "b-end" })], built, 1), "CONCRETE_BAG");
  const three = qtyOf(mergeTakeoff([L("END_POST", 1, { auto: false, id: "b-end" })], built, 3), "CONCRETE_BAG");
  assert.notEqual(one, three, "bagsPerPost is being ignored");
  assert.equal(one, 13);
  assert.equal(three, 11);
  // And the source really carries the rule, rather than this testing a stub.
  const src = read("supabase/functions/_shared/pricing/line-items.ts");
  assert.match(src, /function followEditedPostCounts/, "the helper is gone");
  assert.match(src, /GATE_POST_ROLES/, "the gate-post exception is gone");
});
